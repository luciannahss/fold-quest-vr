// Convert a PDB file into the compact residue table the game uses.
// usage: node tools/prep-pdb.mjs data/1CRN.pdb A src/proteins/crambin.js
//        node tools/prep-pdb.mjs data/3I40.pdb A,B src/proteins/insulin.js   (several chains)
// With several chains, chain k (0-based) gets residue numbers offset by 1000*k so every number is unique
// (chain A: 1..21, chain B: 1001..1030). Output: { residues, disulfides, ligand, ligandName }.
import fs from 'fs';
const [,, file, chainArg = 'A', out] = process.argv;
const chains = chainArg.split(',');
const THREE_TO_ONE = { ALA:'A',ARG:'R',ASN:'N',ASP:'D',CYS:'C',GLU:'E',GLN:'Q',GLY:'G',HIS:'H',ILE:'I',LEU:'L',LYS:'K',MET:'M',PHE:'F',PRO:'P',SER:'S',THR:'T',TRP:'W',TYR:'Y',VAL:'V' };
const lines = fs.readFileSync(file, 'utf8').split('\n');
const V = { sub: (a, b) => a.map((v, i) => v - b[i]), add: (a, b) => a.map((v, i) => v + b[i]), mul: (a, s) => a.map((v) => v * s),
  len: (a) => Math.hypot(...a), norm: (a) => { const L = Math.hypot(...a) || 1; return a.map((v) => v / L); },
  cross: (a, b) => [a[1]*b[2]-a[2]*b[1], a[2]*b[0]-a[0]*b[2], a[0]*b[1]-a[1]*b[0]] };

// ---- atoms per chain
const byChain = chains.map(() => new Map());
for (const l of lines) {
  if (!l.startsWith('ATOM')) continue;
  const ci = chains.indexOf(l[21]);
  if (ci < 0) continue;
  if (l[16] !== ' ' && l[16] !== 'A') continue; // first altloc only
  const n = parseInt(l.slice(22, 26)), name = l.slice(12, 16).trim(), rn = l.slice(17, 20);
  const p = [parseFloat(l.slice(30, 38)), parseFloat(l.slice(38, 46)), parseFloat(l.slice(46, 54))];
  const m = byChain[ci];
  if (!m.has(n)) m.set(n, { n: n + 1000 * ci, c: chains[ci], aa: THREE_TO_ONE[rn], atoms: {} });
  m.get(n).atoms[name] = p;
}
const list = []; // all residues, chain by chain
byChain.forEach((m) => list.push(...[...m.values()].sort((a, b) => a.n - b.n)));
// centre of the whole assembly (mean CA)
const c = [0, 0, 0]; list.forEach((r) => { for (let i = 0; i < 3; i++) c[i] += r.atoms.CA[i] / list.length; });
const shift = (p) => p && V.sub(p, c);
const rnd = (a) => a && a.map((v) => +v.toFixed(3));

const residues = list.map((r, i) => {
  const { N, CA, C, O, CB, SG } = r.atoms;
  const prev = i > 0 && list[i - 1].c === r.c ? list[i - 1].atoms.C : null; // no previous residue at a chain start
  let H = null;
  if (r.aa !== 'P') {
    const a = V.norm(V.sub(N, prev || V.add(N, V.sub(N, CA))));
    const b = V.norm(V.sub(N, CA));
    H = V.add(N, V.mul(V.norm(V.add(a, b)), 1.01));
  }
  let cb = CB;
  if (!cb) { // glycine: ideal virtual C-beta
    const b = V.sub(CA, N), cc = V.sub(C, CA), a = V.cross(b, cc);
    cb = V.add(V.add(V.add(CA, V.mul(a, -0.58273431)), V.mul(b, 0.56802827)), V.mul(cc, -0.54067466));
  }
  const R = r.aa === 'C' && SG ? SG : V.add(CA, V.mul(V.sub(cb, CA), 1.25));
  return { n: r.n, c: r.c, aa: r.aa, N: rnd(shift(N)), CA: rnd(shift(CA)), C: rnd(shift(C)), O: rnd(shift(O)), H: rnd(shift(H)), R: rnd(shift(R)), hasH: r.aa !== 'P' };
});

// ---- secondary structure from HELIX / SHEET records (per chain, with the same offsets)
const ss = {};
chains.forEach((ch, ci) => {
  const off = 1000 * ci;
  for (const l of lines) {
    if (l.startsWith('HELIX') && l[19] === ch) for (let n = parseInt(l.slice(21, 25)); n <= parseInt(l.slice(33, 37)); n++) ss[n + off] = 'H';
    if (l.startsWith('SHEET') && l[21] === ch) for (let n = parseInt(l.slice(22, 26)); n <= parseInt(l.slice(33, 37)); n++) ss[n + off] = 'E';
  }
});
residues.forEach((r) => (r.ss = ss[r.n] || 'C'));

// ---- disulfides by SG-SG distance (this also finds bridges between chains)
const cys = list.filter((r) => r.aa === 'C' && r.atoms.SG), ssb = [];
for (let i = 0; i < cys.length; i++) for (let j = i + 1; j < cys.length; j++) if (V.len(V.sub(cys[i].atoms.SG, cys[j].atoms.SG)) < 2.5) ssb.push([cys[i].n, cys[j].n]);

// ---- bound ligand (e.g. heme): the largest non-water HETATM group, in the same centred frame
const groups = new Map();
for (const l of lines) {
  if (!l.startsWith('HETATM') || !chains.includes(l[21])) continue;
  const rn = l.slice(17, 20).trim();
  if (rn === 'HOH' || rn === 'WAT') continue;
  const name = l.slice(12, 16).trim();
  const e = (l.slice(76, 78).trim() || (name.startsWith('FE') ? 'FE' : name[0])).toUpperCase();
  if (!groups.has(rn)) groups.set(rn, []);
  groups.get(rn).push({ e, p: rnd(shift([parseFloat(l.slice(30, 38)), parseFloat(l.slice(38, 46)), parseFloat(l.slice(46, 54))])) });
}
let ligandName = null, ligand = [];
for (const [rn, atoms] of groups) if (atoms.length > ligand.length) { ligandName = rn; ligand = atoms; }

const json = JSON.stringify({ residues, disulfides: ssb, ligand, ligandName });
fs.writeFileSync(out, out.endsWith('.js') ? `// generated by tools/prep-pdb.mjs from ${file}\nexport default ${json};\n` : json);
console.log(residues.length, 'residues; ss:', residues.map((r) => r.ss).join(''), '; S-S:', JSON.stringify(ssb));
